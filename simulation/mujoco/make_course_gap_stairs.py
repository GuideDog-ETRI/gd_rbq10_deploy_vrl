#!/usr/bin/env python3
"""Generate simulation/terrains/gap_stairs20_25 (sim course, +x):
  flat 2 m from spawn -> gaps 5/10/15/20/25/30 cm (0.65 m deep pits like gap_pit65, 1.5 m flats between)
  -> 20 cm stairs up/down (10 steps, 0.30 m tread, 2 m top) -> flat 2 m -> 25 cm stairs up/down (same) -> finish flat.
Prints the section x positions (stair push triggers, finish x).

  make_course_gap_stairs.py [out_dir] [--steps20 N] [--steps25 N] [--run-up M]
  --run-up: flat between the last (30 cm) gap and the 20 cm stairs (default 1.5 m).
"""
import argparse
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
ap = argparse.ArgumentParser()
ap.add_argument('out', nargs='?', type=Path, default=REPO / 'simulation/terrains/gap_stairs20_25')
ap.add_argument('--steps20', type=int, default=10)
ap.add_argument('--steps25', type=int, default=10)
ap.add_argument('--run-up', type=float, default=1.5)
args = ap.parse_args()
out = args.out
FLAT = 'rgba="0.22 0.42 0.28 1"'; PIT = 'rgba="0.15 0.15 0.15 1"'; STEP = 'rgba="0.42 0.42 0.46 1"'
HALF_W = 0.90; TREAD = 0.30; TOP = 2.0; PIT_DEPTH = 0.65
geoms, marks = [], {}

def box(name, x0, x1, top, rgba, bottom=-1.5):
    geoms.append(f'    <geom name="{name}" class="course" pos="{(x0 + x1) / 2:.3f} 0 {(top + bottom) / 2:.3f}" '
                 f'size="{(x1 - x0) / 2:.3f} {HALF_W:.2f} {(top - bottom) / 2:.3f}" {rgba}/>')

x = -2.0
box('start_flat', x, 2.0, 0.0, FLAT); x = 2.0
for cm in (5, 10, 15, 20, 25, 30):
    w = cm / 100
    box(f'gap_{cm}_bottom', x, x + w, -PIT_DEPTH, PIT, bottom=-PIT_DEPTH - 0.2); marks[f'gap_{cm}'] = round(x, 3); x += w
    run = args.run_up if cm == 30 else 1.5
    box(f'flat_after_gap_{cm}', x, x + run, 0.0, FLAT); x += run

def stairs(tag, rise, STEPS):
    global x
    marks[f'{tag}_up'] = round(x, 3)
    for k in range(STEPS):
        box(f'{tag}_up{k + 1}', x, x + TREAD, rise * (k + 1), STEP); x += TREAD
    marks[f'{tag}_top'] = round(x, 3)
    box(f'{tag}_top', x, x + TOP, rise * STEPS, FLAT); x += TOP
    marks[f'{tag}_down'] = round(x, 3)
    for k in range(STEPS):
        box(f'{tag}_down{k + 1}', x, x + TREAD, rise * (STEPS - 1 - k), STEP); x += TREAD
    marks[f'{tag}_end'] = round(x, 3)

stairs('st20', 0.20, args.steps20)
box('flat_between_stairs', x, x + 2.0, 0.0, FLAT); x += 2.0
stairs('st25', 0.25, args.steps25)
box('finish_flat', x, x + 3.0, 0.0, FLAT); marks['finish_flat'] = round(x, 3); x += 3.0
end = x
names = [g.split('"')[1] for g in geoms]
guards = [
    f'    <geom name="guard_left" class="guard" pos="{(end - 2) / 2:.3f} {HALF_W + .06:.2f} 1.5" size="{(end + 2) / 2:.3f} 0.06 3.0"/>',
    f'    <geom name="guard_right" class="guard" pos="{(end - 2) / 2:.3f} {-HALF_W - .06:.2f} 1.5" size="{(end + 2) / 2:.3f} 0.06 3.0"/>',
    f'    <geom name="guard_start" class="guard" pos="-2.06 0 1.5" size="0.06 {HALF_W + .12:.2f} 3.0"/>',
    f'    <geom name="guard_finish" class="guard" pos="{end + .06:.2f} 0 1.5" size="0.06 {HALF_W + .12:.2f} 3.0"/>']
pairs = ''.join(f'    <pair geom1="{f}" geom2="{n}"/>\n' for n in names for f in ('RR', 'RL', 'FR', 'FL'))
xml = f'''<?xml version="1.0" encoding="utf-8"?>
<mujoco model="gap + stairs 20/25 cm terrain">
  <!-- Generated by simulation/mujoco/make_course_gap_stairs.py. +X: flat 2 m, gaps 5-30 cm (0.65 m pits, 1.5 m flats),
       gap 30 cm -> {args.run_up} m flat -> 20 cm stairs up/down ({args.steps20} steps x 0.30 m tread, 2 m top), flat 2 m,
       25 cm stairs up/down ({args.steps25} steps), finish flat to x={end:.2f}.
       Sections: {marks} -->
  <statistic center="{(end - 2) / 2:.2f} 0 1.0" extent="{(end + 2) / 2 + 2:.1f}"/>
  <visual>
    <headlight diffuse="0.7 0.7 0.7" ambient="0.25 0.25 0.25"/>
    <global azimuth="-125" elevation="-22"/>
  </visual>
  <default>
    <default class="course">
      <geom type="box" friction="0.8 0.8 0.8" priority="2" contype="1" conaffinity="1"/>
    </default>
    <default class="guard">
      <geom type="box" friction="0.3 0.005 0.0001" contype="1" conaffinity="1" rgba="0.55 0.8 0.95 0.18"/>
    </default>
  </default>
  <worldbody>
    <light pos="{end / 2:.1f} 0 8" dir="0 0 -1" directional="true"/>
{chr(10).join(geoms)}
{chr(10).join(guards)}
  </worldbody>
  <contact>
{pairs}  </contact>
</mujoco>
'''
out.mkdir(parents=True, exist_ok=True)
(out / 'environment.xml').write_text(xml)
(out / 'rbq_environment.xml').write_text('<?xml version="1.0" encoding="utf-8"?><mujoco model="rbq gap 5-30 cm + stairs 20/25 cm course">'
                                         '<include file="env/vrl_progression/rbq_payload.xml"/><include file="env/vrl_progression/environment.xml"/></mujoco>')
print(out, f'end x={end:.2f}', marks)
